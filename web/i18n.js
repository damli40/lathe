export const LANGS = ["en", "zh"];

export const strings = {
  en: { ...pitch.en, tool: tool.en },
  zh: { ...pitch.zh, tool: tool.zh },
};

/** Look up "a.b.c" in the dictionary for lang, fill {placeholders}. Falls back to English, then to the key. */
export function t(lang, path, vars) {
  let s = dig(strings[lang], path);
  if (s === undefined) s = dig(strings.en, path);
  if (typeof s !== "string") return path;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
}

function dig(obj, path) {
  let o = obj;
  for (const p of path.split(".")) {
    if (o == null) return undefined;
    o = o[p];
  }
  return o;
}
